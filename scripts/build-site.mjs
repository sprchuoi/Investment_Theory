#!/usr/bin/env node
/**
 * Build a deployable static site in _site/.
 *
 *   node scripts/build-site.mjs            # GitHub Pages: no books, links show LOCAL
 *   BOOKS_MODE=full node scripts/build-site.mjs
 *                                          # self-host: copies the 3.5 GB book library too
 *
 * The default is intentionally safe: the book library is excluded from the
 * artifact. Never publish copyrighted PDFs/EPUBs to a public GitHub Pages site.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "_site");
const BOOKS = path.join(ROOT, "some-investment-books");
const MODE = (process.env.BOOKS_MODE || "pages").toLowerCase();

// Canonical public source for the books. Keep this in sync with .gitmodules
// and assets/js/site-config.js.
const BOOKS_REPO = "https://github.com/bharaniabhishek123/some-investment-books";
const BOOKS_BRANCH = "master";

if (!["pages", "full"].includes(MODE)) {
  console.error('BOOKS_MODE must be "pages" or "full".');
  process.exit(1);
}

for (const required of ["index.html", "assets"]) {
  if (!fs.existsSync(path.join(ROOT, required))) {
    console.error(`Missing required path: ${required}`);
    process.exit(1);
  }
}

if (MODE === "full" && !fs.existsSync(BOOKS)) {
  console.error("BOOKS_MODE=full but some-investment-books/ does not exist.");
  process.exit(1);
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

fs.copyFileSync(path.join(ROOT, "index.html"), path.join(OUT, "index.html"));
fs.cpSync(path.join(ROOT, "assets"), path.join(OUT, "assets"), { recursive: true });
fs.copyFileSync(path.join(ROOT, ".nojekyll"), path.join(OUT, ".nojekyll"));

if (MODE === "full") {
  console.log("Copying some-investment-books/ (this can take a while, ~3.5 GB)…");
  fs.cpSync(BOOKS, path.join(OUT, "some-investment-books"), { recursive: true });
}

const config = `/* Generated by scripts/build-site.mjs — mode: ${MODE} */
window.SITE_CONFIG = {
  booksEnabled: ${MODE === "full" ? "true" : "false"},
  booksRemote: ${MODE === "pages" ? "true" : "false"},
  booksBase: "some-investment-books/",
  booksRemoteBase: "${BOOKS_REPO}/raw/${BOOKS_BRANCH}/",
  booksRepo: "${BOOKS_REPO}",
  deployMode: "${MODE}"
};
`;
fs.writeFileSync(path.join(OUT, "assets", "js", "site-config.js"), config);

function dirSize(dir) {
  let total = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) total += dirSize(p);
    else if (entry.isFile()) total += fs.statSync(p).size;
  }
  return total;
}

const mb = (dirSize(OUT) / 1024 / 1024).toFixed(1);
console.log(`Built _site/ in ${MODE} mode (${mb} MB).`);
console.log(MODE === "pages"
  ? "Books are not copied; the UI links to the public GitHub source repo."
  : "Books were copied; make sure you have the rights and a private/self-hosted target.");
